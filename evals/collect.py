"""
Collect finished runs into the tables the report quotes.

    python -m evals.collect                    # -> RESULTS.md
    python -m evals.collect --runs runs --out RESULTS.md

I wrote this because copying numbers out of a dozen JSON files by hand is how a
transposed digit ends up in a report. Everything here is read from
`runs/*/config.json`, `runs/*/metrics.jsonl` and `runs/*/eval.json`, so the table
cannot disagree with the runs that produced it.

Runs are matched to experiments by name. Fine-tuning runs called `ft-*` are the
rows; each one is paired with the pretraining run recorded in its `init` field,
so the pretraining perplexity and the task accuracy sit on the same line.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

TASKS_ORDER = ["price", "variant_count", "variant_list", "axis_values", "stock",
               "option_check", "sku", "cheapest", "category", "add_to_cart"]


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def last_metric(run_dir: Path, key: str):
    """Final value of a metric, or the best one where lower is better."""
    path = run_dir / "metrics.jsonl"
    if not path.exists():
        return None
    rows = [json.loads(l) for l in path.open(encoding="utf-8") if l.strip()]
    values = [r[key] for r in rows if r.get(key) is not None]
    return min(values) if values else None


def collect(runs_dir: Path) -> list[dict]:
    out = []
    for run in sorted(p for p in runs_dir.iterdir() if p.is_dir()):
        cfg = read_json(run / "config.json")
        if not cfg:
            continue
        row = {
            "run": run.name,
            "stage": cfg.get("stage", "pretrain"),
            "params_m": None,
            "layers": cfg["model"]["n_layers"],
            "emb": cfg["model"]["emb_dim"],
            "ctx": cfg["model"]["context_length"],
            "init": cfg.get("init"),
            "val_loss": last_metric(run, "val_loss"),
            "val_ppl": last_metric(run, "val_perplexity"),
            "eval": read_json(run / "eval.json"),
            "data": cfg.get("data", {}),
        }
        m = cfg["model"]
        # Same formula as GPTConfig.n_params, recomputed here so the table does
        # not depend on importing torch.
        d, v, L, ctx = m["emb_dim"], m["vocab_size"], m["n_layers"], m["context_length"]
        per_block = (4 * d * d + d) + (d * 4 * d + 4 * d) + (4 * d * d + d) + 4 * d
        total = v * d + ctx * d + L * per_block + 2 * d + (0 if m.get("weight_tying", True) else v * d)
        row["params_m"] = total / 1e6
        out.append(row)
    return out


def fmt(x, nd=2, dash="-"):
    return dash if x is None else f"{x:.{nd}f}"


def render(rows: list[dict]) -> str:
    ft = [r for r in rows if r["stage"] == "finetune"]
    pre = {r["run"]: r for r in rows if r["stage"] != "finetune"}
    lines = ["# Results", "",
             "Generated by `python -m evals.collect` from the run directories. ",
             "Do not edit by hand; rerun it instead.", ""]

    if not rows:
        return "\n".join(lines + ["No runs found. Train something first."])

    # Corpus stats come from a PRETRAINING run. A fine-tuning run's `data` block
    # counts instruction pairs, which are a different thing with some of the same
    # key names.
    corpus = next((r["data"] for r in rows
                   if r["stage"] != "finetune" and r["data"].get("documents")), {})
    if corpus:
        n_tr, n_va = corpus.get("train_tokens", 0), corpus.get("val_tokens", 0)
        lines += ["## Corpus", "",
                  f"- {corpus['documents']} documents, {n_tr:,} training tokens, "
                  f"{n_va:,} validation".replace(",", " ")]
        if corpus.get("excluded_products"):
            lines.append(f"- {corpus['excluded_products']} held-out products "
                         f"({corpus['excluded_documents']} documents) excluded from "
                         "pretraining")
        else:
            lines.append("- held-out products were **not** excluded from pretraining")
        lines.append("")

    lines += ["## Pretraining", "",
              "| run | params | layers | width | val loss | perplexity |",
              "|---|---|---|---|---|---|"]
    for r in rows:
        if r["stage"] == "finetune":
            continue
        lines.append(f"| `{r['run']}` | {r['params_m']:.1f}M | {r['layers']} | "
                     f"{r['emb']} | {fmt(r['val_loss'], 4)} | {fmt(r['val_ppl'], 2)} |")

    lines += ["", "## Task accuracy on held-out products", "",
              "Macro-averaged over the ten tasks. `majority` and `retrieval` are the",
              "baseline floors, computed on the same held-out pairs.", "",
              "| run | init | answer ppl | model | majority | retrieval |",
              "|---|---|---|---|---|---|"]
    for r in ft:
        ev = r["eval"] or {}
        s = ev.get("summary", {})
        init = "scratch" if r["init"] and "random" in r["init"] else "pretrained"
        lines.append(
            f"| `{r['run']}` | {init} | {fmt(r['val_ppl'], 2)} | "
            f"**{fmt(s.get('model', {}).get('macro'))}** | "
            f"{fmt(s.get('majority', {}).get('macro'))} | "
            f"{fmt(s.get('retrieval', {}).get('macro'))} |")

    scored = [r for r in ft if r["eval"]]
    if scored:
        lines += ["", "## Per task", "",
                  "| task | " + " | ".join(f"`{r['run']}`" for r in scored) +
                  " | majority | retrieval |",
                  "|---" * (len(scored) + 3) + "|"]
        base = scored[0]["eval"]["summary"]
        for task in TASKS_ORDER:
            cells = [fmt(r["eval"]["summary"]["model"]["per_task"].get(task, {}).get("score"))
                     for r in scored]
            lines.append(
                f"| {task} | " + " | ".join(cells) + " | " +
                fmt(base.get("majority", {}).get("per_task", {}).get(task, {}).get("score")) +
                " | " +
                fmt(base.get("retrieval", {}).get("per_task", {}).get(task, {}).get("score")) +
                " |")

        lines += ["", "## Strict exact match", "",
                  "The whole answer string, character for character. Reported next to the",
                  "task scores because those are containment checks and inflate.", "",
                  "| run | exact match |", "|---|---|"]
        for r in scored:
            lines.append(f"| `{r['run']}` | {fmt(r['eval']['summary']['model']['exact'])} |")

    lines += ["", "---", "",
              "Every score above comes from greedy decoding unless the run's `eval.json`",
              "says otherwise. See `FINDINGS.md` for what the numbers mean and",
              "`RUNBOOK.md` for how to reproduce them."]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", type=Path, default=Path("runs"))
    ap.add_argument("--out", type=Path, default=Path("RESULTS.md"))
    args = ap.parse_args(argv)

    if not args.runs.exists():
        print(f"{args.runs} does not exist. Train something first.")
        return 1

    rows = collect(args.runs)
    args.out.write_text(render(rows), encoding="utf-8")
    n_eval = sum(1 for r in rows if r["eval"])
    print(f"{len(rows)} runs, {n_eval} with evaluation -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
